    window1 = int(f1 * fs / 2) + 1 if int(f1 * fs / 2) % 2 == 0 else int(f1 * fs / 2)
    window2 = int(f2 * fs / 2) + 1 if int(f2 * fs / 2) % 2 == 0 else int(f2 * fs / 2)
    out1 = smooth(signal, window1)
    out2 = smooth(out1, window2)
    bwr_signal = signal - out2
    return bwr_signal


